"""Fetch recycling points from OpenStreetMap for a few Indian cities and write web/app/dropoff_data.js (the "Nearest drop-off" page).

Source: OpenStreetMap contributors, Open Database Licence 1.0 (https://www.openstreetmap.org/copyright), through the public Overpass API.
Method: every node or way tagged amenity=recycling inside a rectangle around each city centre (not the municipal boundary). Nothing is added, guessed or ranked.
A city whose query keeps failing is written as "not_checked" with the reason, never as zero points.
Usage (repo root):  python tools/fetch_osm_dropoff.py        (about 2 to 5 minutes; be polite to the public server, do not loop it)
The client name below is generic on purpose: it carries no personal details.
"""
import json
import os
import sys
import time
import urllib.parse
import urllib.request

UA = "kachra-satya-dropoff/1.0 (static data build)"
URL = "https://overpass-api.de/api/interpreter"
CITIES = {   # name: (south, west, north, east)
    "Bengaluru": (12.80, 77.45, 13.20, 77.80),
    "Delhi": (28.40, 76.95, 28.90, 77.40),
    "Kochi": (9.90, 76.20, 10.10, 76.40),
    "Mumbai": (18.85, 72.75, 19.30, 73.05),
    "Hyderabad": (17.20, 78.20, 17.65, 78.70),
    "Chennai": (12.90, 80.10, 13.25, 80.35),
}
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "web", "app", "dropoff_data.js")


def fetch(bbox):
    s, w, n, e = bbox
    q = '[out:json][timeout:90];(node["amenity"="recycling"](%s,%s,%s,%s);way["amenity"="recycling"](%s,%s,%s,%s););out center tags;' % (s, w, n, e, s, w, n, e)
    req = urllib.request.Request(URL, data=urllib.parse.urlencode({"data": q}).encode(), headers={"User-Agent": UA, "Accept": "application/json"})
    with urllib.request.urlopen(req, timeout=150) as r:
        return json.loads(r.read().decode("utf-8"))


def point(el):
    t = el.get("tags", {})
    lat, lon = (el.get("lat"), el.get("lon")) if el["type"] == "node" else (el.get("center", {}).get("lat"), el.get("center", {}).get("lon"))
    if lat is None or lon is None:
        return None
    kinds = sorted(k[len("recycling:"):] for k, v in t.items() if k.startswith("recycling:") and v == "yes")
    return {"id": "%s/%s" % (el["type"], el["id"]), "lat": round(lat, 6), "lon": round(lon, 6), "name": t.get("name"), "kinds": kinds, "operator": t.get("operator"), "hours": t.get("opening_hours")}


def main():
    out = {}
    for name, bbox in CITIES.items():
        entry = {"bbox": list(bbox), "status": "not_checked", "reason": "", "osm_base": None, "points": []}
        for attempt in range(3):
            try:
                d = fetch(bbox)
                entry.update(status="ok", reason="", osm_base=d.get("osm3s", {}).get("timestamp_osm_base"), points=[p for p in map(point, d["elements"]) if p])
                break
            except Exception as ex:   # server busy, timeout, bad reply: wait and retry, then say so
                entry["reason"] = "%s: %s" % (type(ex).__name__, str(ex)[:80])
                print(name, "attempt", attempt + 1, "failed:", entry["reason"], file=sys.stderr)
                time.sleep(25)
        out[name] = entry
        print(name, entry["status"], len(entry["points"]), flush=True)
        time.sleep(8)
    data = {"retrieved": time.strftime("%Y-%m-%d"), "source": "OpenStreetMap contributors, Open Database Licence 1.0 (https://www.openstreetmap.org/copyright)",
            "method": "Nodes and ways tagged amenity=recycling inside a rectangle around each city centre, read through the Overpass API. Not verified on the ground.", "cities": out}
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/fetch_osm_dropoff.py. Do not edit by hand. Data (c) OpenStreetMap contributors, ODbL 1.0. */\nwindow.KS_DROPOFF = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
